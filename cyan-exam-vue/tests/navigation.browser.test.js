import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.EXAM_TEST_URL || 'http://127.0.0.1:5177'

test('navigation branding, collapse, mobile drawer and dark mode', async t => {
  const response = await fetch(`${base}/dev-api/login`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: 'demo_owner', password: process.env.EXAM_DEMO_PASSWORD })
  })
  const login = await response.json()
  assert.equal(login.code, 200)
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  t.after(() => browser.close())
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  await context.addCookies([{ name: 'Exam-Token-127-0-0-1-8181', value: login.token, url: base }])
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${base}/exam/onsite`)
  const sidebar = page.locator('#app-sidebar')
  await sidebar.waitFor()
  assert.equal(await sidebar.locator('img').count(), 0)
  assert.equal(await page.locator('link[rel="icon"]').getAttribute('href'), 'data:,')
  await page.getByRole('button', { name: '收起菜单', exact: true }).waitFor()
  await page.locator('.el-loading-mask').waitFor({ state: 'hidden' })
  await page.screenshot({ path: 'tests/navigation-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '收起菜单', exact: true }).click()
  await page.waitForTimeout(400)
  assert.equal(Math.round((await sidebar.boundingBox()).width), 64)
  assert.equal(Math.round((await page.locator('.main-container').boundingBox()).x), 64)
  await page.screenshot({ path: 'tests/navigation-collapsed.png', fullPage: true })
  await page.getByRole('button', { name: '展开菜单', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(400)
  assert.equal(await sidebar.evaluate(el => el.inert), true)
  await page.getByRole('button', { name: '展开菜单', exact: true }).click()
  await page.waitForTimeout(400)
  assert.equal(await sidebar.evaluate(el => el.inert), false)
  assert.equal(Math.round((await sidebar.boundingBox()).x), 0)
  assert.equal(await sidebar.getByText('现场任务与评分', { exact: true }).isVisible(), true)
  await page.screenshot({ path: 'tests/navigation-mobile.png', fullPage: true })
  await page.locator('.drawer-bg').click({ position: { x: 370, y: 200 } })
  await page.waitForTimeout(400)
  assert.equal(await sidebar.evaluate(el => el.inert), true)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '展开菜单', exact: true }).click()
  await page.locator('.theme-switch-wrapper').click()
  await page.mouse.move(700, 500)
  await page.waitForTimeout(800)
  assert.equal(await page.locator('html').evaluate(el => el.classList.contains('dark')), true)
  await page.screenshot({ path: 'tests/navigation-dark.png', fullPage: true })
  await page.evaluate(() => localStorage.setItem('layout-setting', JSON.stringify({ sidebarLogo: false })))
  await page.reload()
  await sidebar.waitFor()
  assert.equal(await sidebar.locator('.sidebar-logo-container').count(), 0)
  const heights = await sidebar.evaluate(el => [el.clientHeight, el.querySelector('.el-scrollbar').clientHeight])
  assert.equal(heights[0], heights[1])
  assert.deepEqual(errors, [])
})
